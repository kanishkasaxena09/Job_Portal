/* ==========================================================================
   Accessor Helpers
   ========================================================================== */
const PortalData = {
  /* Returns full company object for a job */
  getCompanyForJob(jobId) {
    const job = PORTAL_DATA.jobs.find(j => j.id === jobId);
    if (!job) return null;
    return PORTAL_DATA.companies.find(c => c.id === job.company) || null;
  },

  /* Returns company by id */
  getCompanyById(id) {
    return PORTAL_DATA.companies.find(c => c.id === Number(id)) || null;
  },

  /* Returns job by id */
  getJobById(id) {
    return PORTAL_DATA.jobs.find(j => j.id === Number(id)) || null;
  },

  /* Returns jobs filtered by category */
  getJobsByCategory(categoryId) {
    return PORTAL_DATA.jobs.filter(j => j.category === categoryId);
  },

  /* Returns jobs by company */
  getJobsByCompany(companyId) {
    return PORTAL_DATA.jobs.filter(j => j.company === companyId);
  },

  /* Returns category label by id */
  getCategoryName(id) {
    const cat = PORTAL_DATA.categories.find(c => c.id === id);
    return cat ? cat.name : '';
  },

  /* Searches jobs by title, tag, company name, or location */
  searchJobs(query) {
    const q = query.toLowerCase().trim();
    if (!q) return PORTAL_DATA.jobs;

    return PORTAL_DATA.jobs.filter(job => {
      const company = this.getCompanyForJob(job.id);
      const searchable = [
        job.title,
        job.location,
        job.type,
        job.tags.join(' '),
        company ? company.name : '',
        this.getCategoryName(job.category),
      ].join(' ').toLowerCase();

      return searchable.includes(q);
    });
  },
};